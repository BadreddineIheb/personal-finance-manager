const NS = 'http://www.w3.org/2000/svg';

/** Retourne un élément <svg> pour l'icône `name`. */
export function icon(name, className = 'icon') {
  const svg = document.createElementNS(NS, 'svg');
  svg.setAttribute('class', className);
  svg.setAttribute('viewBox', '0 0 24 24');
  svg.setAttribute('aria-hidden', 'true');
  svg.setAttribute('focusable', 'false');
  svg.innerHTML = P[name] ?? P.dots; // constante interne, jamais une saisie utilisateur
  return svg;
}

/** Remplace chaque élément [data-icon] du document par l'icône correspondante. */
export function hydrateIcons(root = document) {
  for (const el of root.querySelectorAll('[data-icon]')) {
    el.replaceChildren(icon(el.dataset.icon, el.dataset.iconClass || 'icon'));
  }
}

